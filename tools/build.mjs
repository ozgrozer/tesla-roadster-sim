// Bundles js/main.js, everything it imports and the vendored three.js into dist/roadster.js:
// one classic <script>, so index.html opens straight from disk (file://) without a server.
//
//   node tools/build.mjs           build once
//   node tools/build.mjs --watch   rebuild whenever js/ changes
//
// Zero dependencies. It understands the import/export forms this project uses (named imports,
// namespace imports, exported declarations and export lists) and rejects anything else loudly.
import { dirname, relative, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { readFileSync, writeFileSync, mkdirSync, watch } from 'node:fs'

const ROOT = resolve(fileURLToPath(new URL('..', import.meta.url)))
const ENTRY = resolve(ROOT, 'js/main.js')
export const OUT = resolve(ROOT, 'dist/roadster.js')
const THREE = resolve(ROOT, 'vendor/three/three.module.js')
const ADDONS = resolve(ROOT, 'vendor/three/addons')

const IMPORT_RE = /^import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"]\s*;?[ \t]*$/gm
const DECL_RE = /^export\s+((?:async\s+)?function\*?|class|const|let|var)\s+([A-Za-z_$][\w$]*)/gm
const LIST_RE = /^export\s*\{([^}]*)\}\s*;?[ \t]*$/gm

function resolveSpec (spec, from) {
  if (spec === 'three') return THREE
  if (spec.startsWith('three/addons/')) return resolve(ADDONS, spec.slice(13))
  if (spec.startsWith('.')) return resolve(dirname(from), spec)
  throw new Error(`${relative(ROOT, from)}: unsupported import "${spec}"`)
}

function importsOf (file, src) {
  return [...src.matchAll(IMPORT_RE)].map(m => resolveSpec(m[2], file))
}

// depth-first, dependencies before dependants (the order ES modules evaluate in)
function collect (file, seen = new Map()) {
  if (seen.has(file)) return seen
  const src = readFileSync(file, 'utf8')
  seen.set(file, null)
  for (const dep of importsOf(file, src)) collect(dep, seen)
  seen.delete(file)
  seen.set(file, src)
  return seen
}

function transform (file, src, ids) {
  const name = relative(ROOT, file)
  if (/^export\s+(default\b|\*)/m.test(src)) {
    throw new Error(`${name}: export default / export * are not supported`)
  }
  if (/\bimport\s*\(|import\.meta/.test(src)) {
    throw new Error(`${name}: dynamic import and import.meta are not supported`)
  }
  const exported = []
  let code = src.replace(IMPORT_RE, (_, clause, spec) => {
    const id = ids.get(resolveSpec(spec, file))
    clause = clause.trim()
    if (clause.startsWith('* as ')) {
      return `const ${clause.slice(5).trim()} = __require(${id})`
    }
    if (clause.startsWith('{') && clause.endsWith('}')) {
      const names = clause
        .slice(1, -1)
        .split(',')
        .map(s => s.trim())
        .filter(Boolean)
        .map(s => s.replace(/\s+as\s+/, ': '))
      return `const { ${names.join(', ')} } = __require(${id})`
    }
    throw new Error(`${name}: unsupported import clause "${clause}"`)
  })
  code = code.replace(DECL_RE, (_, kind, local) => {
    exported.push([local, local])
    return `${kind} ${local}`
  })
  code = code.replace(LIST_RE, (_, list) => {
    for (const part of list
      .split(',')
      .map(s => s.trim())
      .filter(Boolean)) {
      const [local, as] = part.split(/\s+as\s+/)
      exported.push([as || local, local])
    }
    return ''
  })
  const getters = exported.map(
    ([as, local]) => `${JSON.stringify(as)}: () => ${local}`
  )
  return [
    `// ---- ${name}`,
    `__define(${ids.get(file)}, function (__exports) {`,
    code.trimEnd(),
    `__export(__exports, { ${getters.join(', ')} })`,
    '})'
  ].join('\n')
}

export function bundle () {
  const modules = collect(ENTRY)
  const ids = new Map([...modules.keys()].map((file, i) => [file, i]))
  const parts = [...modules].map(([file, src]) => transform(file, src, ids))
  return `// Generated by tools/build.mjs from js/ and vendor/three: do not edit. Rebuild with: npm run build
;(function () {
'use strict'
const __defs = [], __cache = []
function __define (id, fn) { __defs[id] = fn }
function __export (target, getters) {
  for (const k in getters) Object.defineProperty(target, k, { get: getters[k], enumerable: true })
}
function __require (id) {
  if (!__cache[id]) { __cache[id] = {}; __defs[id](__cache[id]) }
  return __cache[id]
}
${parts.join('\n\n')}
__require(${ids.get(ENTRY)})
})()
`
}

export function build () {
  const out = bundle()
  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, out)
  return out
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const run = () => {
    try {
      const out = build()
      console.log(
        `Built ${relative(ROOT, OUT)} (${(out.length / 1024).toFixed(0)} KB)`
      )
    } catch (err) {
      console.error(`Build failed: ${err.message}`)
      if (!process.argv.includes('--watch')) process.exit(1)
    }
  }
  run()
  if (process.argv.includes('--watch')) {
    let timer = null
    watch(resolve(ROOT, 'js'), { recursive: true }, () => {
      clearTimeout(timer)
      timer = setTimeout(run, 80)
    })
    console.log('Watching js/ for changes (Ctrl+C to stop)')
  }
}
